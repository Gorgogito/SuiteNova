// Writes packages/theme-core/src/office-data.ts from the colour and font schemes that Office installs ("Document Themes 16"): the values of
// the schemes are read from the real files, not remembered. Usage: node scripts/office-theme/gen-catalog.mjs
import fs from 'node:fs';

const DIR = process.env.OFFICE_THEMES ?? 'C:/Program Files/Microsoft Office/root/Document Themes 16';
const SLOTS = ['dk1', 'lt1', 'dk2', 'lt2', 'accent1', 'accent2', 'accent3', 'accent4', 'accent5', 'accent6', 'hlink', 'folHlink'];
const SPANISH = {
  'Office 2013 - 2022': 'Office', 'Office 2007 - 2010': 'Office 2007-2010', Grayscale: 'Escala de grises', 'Blue Warm': 'Azul cálido', Blue: 'Azul', 'Blue II': 'Azul II',
  'Blue Green': 'Azul verde', Green: 'Verde', 'Green Yellow': 'Verde amarillo', Yellow: 'Amarillo', 'Yellow Orange': 'Amarillo anaranjado', Orange: 'Naranja',
  'Orange Red': 'Naranja rojizo', 'Red Orange': 'Rojo anaranjado', Red: 'Rojo', 'Red Violet': 'Rojo violeta', Violet: 'Violeta', 'Violet II': 'Violeta II',
  Median: 'Mediana', Paper: 'Papel', Marquee: 'Marquesina', Slipstream: 'Slipstream', Aspect: 'Aspecto',
};
const ORDER = ['Office 2013 - 2022', 'Office 2007 - 2010', 'Grayscale', 'Blue Warm', 'Blue', 'Blue II', 'Blue Green', 'Green', 'Green Yellow', 'Yellow', 'Yellow Orange', 'Orange', 'Orange Red', 'Red Orange', 'Red', 'Red Violet', 'Violet', 'Violet II', 'Median', 'Paper', 'Marquee', 'Slipstream', 'Aspect'];
const id = (s) => s.replace(/[^A-Za-z0-9]+(.)?/g, (_m, c) => (c ? c.toUpperCase() : '')).replace(/^./, (c) => c.toLowerCase());

const colors = ORDER.map((name) => {
  const x = fs.readFileSync(`${DIR}/Theme Colors/${name}.xml`, 'utf8');
  const hex = SLOTS.map((s) => {
    const m = new RegExp(`<a:${s}>.*?(?:srgbClr val|lastClr)="([0-9A-Fa-f]{6})"`, 's').exec(x);
    if (!m) throw new Error(`${name}: ${s}`);
    return `#${m[1].toLowerCase()}`;
  });
  return [id(SPANISH[name] === 'Office' ? 'office' : name), SPANISH[name], hex];
});

const fonts = fs
  .readdirSync(`${DIR}/Theme Fonts`)
  .filter((f) => f.endsWith('.xml'))
  .map((f) => {
    const x = fs.readFileSync(`${DIR}/Theme Fonts/${f}`, 'utf8');
    const face = (k) => /<a:latin\s+typeface="([^"]*)"/.exec(new RegExp(`<a:${k}>[\\s\\S]*?</a:${k}>`).exec(x)[0])[1];
    const name = f.replace(/\.xml$/, '');
    return [name, face('majorFont'), face('minorFont')];
  });
const office = fonts.find((f) => f[0] === 'Office 2013 - 2022');
const rest = fonts.filter((f) => f !== office);

const out = `// Generated by scripts/office-theme/gen-catalog.mjs from the schemes that Office installs. Do not edit by hand.
/** [id, name, the 12 colours dk1 lt1 dk2 lt2 accent1-6 hlink folHlink] */
export const OFFICE_COLORS: [string, string, string[]][] = ${JSON.stringify(colors, null, 1).replace(/\n\s*/g, ' ')};

/** [file name, headings font, body font] */
export const OFFICE_FONTS: [string, string, string][] = ${JSON.stringify([office, ...rest], null, 1).replace(/\n\s*/g, ' ')};
`;
fs.writeFileSync('packages/theme-core/src/office-data.ts', out);
console.log(`colores: ${colors.length}, fuentes: ${fonts.length}`);
